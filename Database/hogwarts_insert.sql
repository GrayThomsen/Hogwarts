        name varchar(255) NOT NULL UNIQUE
    );

CREATE TABLE
    public.staff (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        first_name varchar(100) NOT NULL,
        last_name varchar(100),
        role varchar(255)
    );

CREATE TABLE
    public.houses (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(255) NOT NULL UNIQUE,
        house_ghost integer UNIQUE REFERENCES public.staff (id),
        head_of_house integer UNIQUE REFERENCES public.staff (id)
    );

CREATE TABLE
    public.students (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        first_name varchar(100) NOT NULL,
        last_name varchar(100),
        house integer REFERENCES public.houses (id)
    );

CREATE TABLE
    public.student_classes (
        student_id integer NOT NULL REFERENCES public.students (id),
        class_id integer NOT NULL REFERENCES public.classes (id),
        year integer NOT NULL CHECK (year BETWEEN 1 AND 7),
        PRIMARY KEY (student_id, class_id, year)
    );

CREATE TABLE
    public.teacher_classes (
        teacher_id integer NOT NULL REFERENCES public.staff (id),
        class_id integer NOT NULL REFERENCES public.classes (id),
        PRIMARY KEY (teacher_id, class_id)
    );

